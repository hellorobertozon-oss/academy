type AcademyContextValue = {
  language: AcademyLanguage;
  isAdmin: boolean;
  setLanguage: (language: AcademyLanguage) => void;
  setPreviewLanguage: (language: AcademyLanguage) => void;
  t: (key: CopyKey) => string;
  completedLessons: CopyKey[];
  completeLesson: (lesson: CopyKey) => void;
};

const AcademyContext = createContext<AcademyContextValue | null>(null);
const LANGUAGE_EVENT = "xzone-academy-language-change";
const PROGRESS_EVENT = "xzone-academy-progress-change";
const COMPLETED_LESSONS_STORAGE_KEY = "xzone-academy-completed-lessons";

function readCompletedLessons(): CopyKey[] {
  try {
    const stored = window.localStorage.getItem(COMPLETED_LESSONS_STORAGE_KEY);
    if (!stored) return [];

    const parsed: unknown = JSON.parse(stored);
    if (!Array.isArray(parsed)) return [];

    return parsed.filter(
      (lesson): lesson is CopyKey =>
        typeof lesson === "string" && Object.prototype.hasOwnProperty.call(COPY.pl, lesson),
    );
  } catch {
    return [];
  }
}

function subscribeToLanguage(notify: () => void) {
  window.addEventListener(LANGUAGE_EVENT, notify);
  window.addEventListener("storage", notify);
  return () => {
    window.removeEventListener(LANGUAGE_EVENT, notify);
    window.removeEventListener("storage", notify);
  };
}

function getStoredLanguage(): AcademyLanguage {
  const stored = window.localStorage.getItem("xzone-academy-language");
  return isAcademyLanguage(stored) ? stored : "pl";
}

function getServerLanguage(): AcademyLanguage {
  return "pl";
}

export function AcademyProvider({ children }: { children: ReactNode }) {
  const router = useRouter();
  const language = useSyncExternalStore(subscribeToLanguage, getStoredLanguage, getServerLanguage);
  const [role, setRole] = useState<"admin" | "employee" | null>(null);
  const [completedLessons, setCompletedLessons] = useState<CopyKey[]>([]);
  const didChangeLanguage = useRef(false);

  useEffect(() => {
    let active = true;
    void readAcademyViewerContextAction().then(({ preferredLanguage, role: currentRole }) => {
      if (!active) return;
      setRole(currentRole);
      if (didChangeLanguage.current || !isAcademyLanguage(preferredLanguage)) return;
      window.localStorage.setItem("xzone-academy-language", preferredLanguage);
      window.dispatchEvent(new Event(LANGUAGE_EVENT));
    }).catch(() => {});

    return () => {
      active = false;
    };
  }, []);

  useEffect(() => {
    const syncCompletedLessons = () => setCompletedLessons(readCompletedLessons());
    syncCompletedLessons();
    window.addEventListener(PROGRESS_EVENT, syncCompletedLessons);
    window.addEventListener("storage", syncCompletedLessons);

    return () => {
      window.removeEventListener(PROGRESS_EVENT, syncCompletedLessons);
      window.removeEventListener("storage", syncCompletedLessons);
    };
  }, []);

  const setLanguage = useCallback((nextLanguage: AcademyLanguage) => {
    didChangeLanguage.current = true;
    void updatePreferredLanguageAction(nextLanguage).then((saved) => {
      if (!saved) return;
      window.localStorage.setItem("xzone-academy-language", nextLanguage);
      window.dispatchEvent(new Event(LANGUAGE_EVENT));
      router.refresh();
    }).catch(() => {});
  }, [router]);
  const setPreviewLanguage = useCallback((nextLanguage: AcademyLanguage) => {
    didChangeLanguage.current = true;
    try {
      window.localStorage.setItem("xzone-academy-language", nextLanguage);
    } catch {
      // Keep the current language for this session when browser storage is unavailable.
    }
    window.dispatchEvent(new Event(LANGUAGE_EVENT));
    router.refresh();
  }, [router]);
  const completeLesson = useCallback((lesson: CopyKey) => {
    if (completedLessons.includes(lesson)) return;

    const next = [...completedLessons, lesson];
    try {
      window.localStorage.setItem(COMPLETED_LESSONS_STORAGE_KEY, JSON.stringify(next));
      window.dispatchEvent(new Event(PROGRESS_EVENT));
    } catch {
      // Keep this session's progress even when browser storage is unavailable.
    }
    setCompletedLessons(next);
  }, [completedLessons]);
  const isAdmin = role === "admin";
  const t = useCallback((key: CopyKey) => {
    if (language === "pl") return COPY.pl[key];
    if (language === "en") return COPY.en[key];
    return LOCALIZED_COPY[language][key] ?? COPY.en[key];
  }, [language]);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(
    () => ({ language, isAdmin, setLanguage, setPreviewLanguage, t, completedLessons, completeLesson }),
    [language, isAdmin, setLanguage, setPreviewLanguage, t, completedLessons, completeLesson],
  );

  return (
    <DirectionProvider locale={{ pl: "pl-PL", en: "en-US", de: "de-DE", cs: "cs-CZ", fr: "fr-FR" }[language]}>
      <AcademyContext.Provider value={value}>{children}</AcademyContext.Provider>
    </DirectionProvider>
  );
}

export function useAcademy() {
  const context = useContext(AcademyContext);
  if (!context) throw new Error("useAcademy must be used inside AcademyProvider.");
  return context;
}

import type { AcademyLanguage } from "@/components/academy-provider";

export type LocalizedGameText = Record<AcademyLanguage, string>;

export type CustomerAdviceTurn =
  | {
      kind: "product";
      prompt: LocalizedGameText;
      productIds: string[];
      bestProductIds: string[];
      acceptableProductIds?: string[];
      acceptableProductSets?: string[][];
      selectionMode?: "single" | "multiple";
    }
  | {
      kind: "answer";
      prompt: LocalizedGameText;
      answers: Array<{
        id: string;
        label: LocalizedGameText;
        correct: boolean;
      }>;
    };

type CustomerAdviceAnswerTurn = Extract<CustomerAdviceTurn, { kind: "answer" }>;
type CustomerAdviceOptionalQuestion = {
  afterTurnIndex: number;
  turn: CustomerAdviceAnswerTurn;
};

export type CustomerAdviceScenario = {
  id: string;
  difficulty: "easy" | "medium" | "hard";
  turns: CustomerAdviceTurn[];
  optionalQuestions?: CustomerAdviceOptionalQuestion[];
};

const text = (pl: string, en: string, de: string, cs: string, fr: string): LocalizedGameText => ({ pl, en, de, cs, fr });

const answer = (id: string, correct: boolean, pl: string, en: string, de: string, cs: string, fr: string) => ({
  id,
  correct,
  label: text(pl, en, de, cs, fr),
});

const productScenario = (
  id: string,
  difficulty: CustomerAdviceScenario["difficulty"],
  prompt: LocalizedGameText,
  productIds: string[],
  bestProductIds: string[],
  acceptableProductIds: string[] = [],
  followUp?: CustomerAdviceAnswerTurn,
): CustomerAdviceScenario => {
  const turns: CustomerAdviceTurn[] = [{ kind: "product", prompt, productIds, bestProductIds, acceptableProductIds }];
  if (followUp) turns.push(followUp);
  return { id, difficulty, turns };
};

